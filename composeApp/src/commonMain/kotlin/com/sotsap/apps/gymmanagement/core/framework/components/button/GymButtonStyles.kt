package com.sotsap.apps.gymmanagement.core.framework.components.button

/**
 * Defines the different visual styles available for GymButton components.
 *
 * Each style represents a distinct look and feel, allowing for consistent
 * button presentation throughout the application.
 *
 * - `Primary`:  The main call-to-action button, typically with a solid background.
 * - `Secondary`: An alternative action button, often with a less prominent style than Primary.
 * - `Text`:    A button that appears as plain text, suitable for less important actions.
 * - `Outline`: A button with a border and transparent background, used for secondary or tertiary actions.
 * - `Link`:    A button styled to resemble a hyperlink.
 */
enum class GymButtonStyles { Primary, Secondary, Text, Outline, Link }